/**
 * Generate the contact section's dot-matrix world map.
 *
 *   node scripts/build-world-map.mjs
 *
 * Samples Natural Earth's 110m land polygons (public domain, via world-atlas)
 * onto a latitude/longitude grid and writes the land points to
 * `src/data/worldMap.ts`.
 *
 * Done at build time, not runtime: the source TopoJSON is 55KB and decoding it
 * needs a projection library, while the output is a flat array of small
 * integers the component renders directly. The map never changes, so paying for
 * it on every page load would be paying for nothing.
 *
 * Scanline rather than point-in-polygon per dot: for each row of latitude,
 * intersect every ring once, sort the crossings and fill the spans between
 * them. Exact, and orders of magnitude cheaper than testing every point.
 */

import { writeFile } from "node:fs/promises";

const SOURCE = "https://unpkg.com/world-atlas@2/land-110m.json";

/** Grid resolution in degrees. Finer looks like a photo, coarser loses coastlines. */
const STEP = 2;
/** Latitudes worth drawing: below this Antarctica dominates, above it is empty ocean. */
const LAT_MIN = -56;
const LAT_MAX = 78;

const topology = await (await fetch(SOURCE)).json();
const { scale, translate } = topology.transform;

/** TopoJSON stores arcs quantised and delta-encoded. */
function decodeArc(arc) {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
}

const arcs = topology.arcs.map(decodeArc);

/** A negative index means "this arc, reversed" — encoded as ~i. */
function ring(indices) {
  const points = [];
  for (const index of indices) {
    const arc = index < 0 ? [...arcs[~index]].reverse() : arcs[index];
    points.push(...(points.length ? arc.slice(1) : arc));
  }
  return points;
}

const rings = [];
for (const geometry of topology.objects.land.geometries) {
  const polygons = geometry.type === "Polygon" ? [geometry.arcs] : geometry.arcs;
  for (const poly of polygons) for (const r of poly) rings.push(ring(r));
}

const dots = [];
for (let lat = LAT_MAX; lat >= LAT_MIN; lat -= STEP) {
  // every x where a ring crosses this latitude
  const crossings = [];
  for (const points of rings) {
    for (let i = 0; i < points.length - 1; i++) {
      const [x1, y1] = points[i];
      const [x2, y2] = points[i + 1];
      if (y1 === y2) continue;
      if (lat < Math.min(y1, y2) || lat >= Math.max(y1, y2)) continue;
      crossings.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
    }
  }
  crossings.sort((a, b) => a - b);

  // even-odd: land lies between crossing pairs, which also carves out holes
  for (let lon = -180; lon <= 180; lon += STEP) {
    let inside = false;
    for (const x of crossings) {
      if (x > lon) break;
      inside = !inside;
    }
    if (inside) dots.push([Math.round(lon), Math.round(lat)]);
  }
}

const file = `// GENERATED by scripts/build-world-map.mjs — do not edit by hand.
//
// Land points from Natural Earth 110m (public domain), sampled every ${STEP}°
// between ${LAT_MIN}° and ${LAT_MAX}° latitude. Coordinates are [longitude, latitude];
// the component projects them, so the data stays independent of how it is drawn.

export const WORLD_STEP = ${STEP};
export const WORLD_BOUNDS = { latMin: ${LAT_MIN}, latMax: ${LAT_MAX} };

export const WORLD_DOTS: [number, number][] = ${JSON.stringify(dots)};
`;

await writeFile(new URL("../src/data/worldMap.ts", import.meta.url), file);
console.log(`${dots.length} land dots at ${STEP}° → src/data/worldMap.ts`);
