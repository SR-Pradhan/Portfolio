/**
 * Generate the contact section's dot-matrix world map.
 *
 *   node scripts/build-world-map.mjs
 *
 * Samples Natural Earth's 110m land polygons (public domain, via world-atlas)
 * onto a latitude/longitude grid and writes the land points to
 * `src/data/worldMap.ts`.
 *
 * Done at build time, not runtime: the source TopoJSON is 55KB and decoding it
 * needs a projection library, while the output is a flat array of small
 * integers the component renders directly. The map never changes, so paying for
 * it on every page load would be paying for nothing.
 *
 * Scanline rather than point-in-polygon per dot: for each row of latitude,
 * intersect every ring once, sort the crossings and fill the spans between
 * them. Exact, and orders of magnitude cheaper than testing every point.
 */

import { writeFile } from "node:fs/promises";

const SOURCE = "https://unpkg.com/world-atlas@2/countries-110m.json";

/** Decimal places kept per coordinate. One is ~11km at the equator, which is
 *  finer than a 360-unit-wide map can show, and halves the file. */
const DECIMALS = 1;
/** Latitudes worth drawing: below this Antarctica dominates, above it is empty ocean. */
const LAT_MIN = -56;
const LAT_MAX = 78;

const topology = await (await fetch(SOURCE)).json();
const { scale, translate } = topology.transform;

/** TopoJSON stores arcs quantised and delta-encoded. */
function decodeArc(arc) {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
}

const arcs = topology.arcs.map(decodeArc);

/** A negative index means "this arc, reversed" — encoded as ~i. */
function ring(indices) {
  const points = [];
  for (const index of indices) {
    const arc = index < 0 ? [...arcs[~index]].reverse() : arcs[index];
    points.push(...(points.length ? arc.slice(1) : arc));
  }
  return points;
}

/**
 * Every country's rings, projected and rounded, as one path.
 *
 * Outlines rather than a dot grid: dots read as a texture, and at any size that
 * fits beside a form the coastlines turn to mush. Borders draw the same map in
 * a tenth of the ink, and countries are legible at a glance.
 *
 * `land` would give a smaller file, but it has no internal borders — and the
 * borders are most of what makes a world map look like a map.
 */
const commands = [];
for (const geometry of topology.objects.countries.geometries) {
  const polygons = geometry.type === "Polygon" ? [geometry.arcs] : geometry.arcs;
  for (const poly of polygons) {
    for (const r of poly) {
      const points = ring(r);
      let d = "";
      let last = "";
      let previousLng = null;
      for (const [lng, lat] of points) {
        // equirectangular, and flipped: latitude grows upward, y grows down
        const x = (lng + 180).toFixed(DECIMALS);
        const y = (LAT_MAX - lat).toFixed(DECIMALS);
        const step = `${x} ${y}`;

        // Countries that straddle the ±180 meridian — Russia, Fiji, Antarctica
        // — come back with consecutive vertices at opposite edges of the world.
        // Joined with a line, that draws a stripe straight across the map, which
        // is exactly what the first render showed. Break the subpath instead.
        const wrapped = previousLng !== null && Math.abs(lng - previousLng) > 180;
        previousLng = lng;

        // rounding turns neighbouring vertices into duplicates; dropping them
        // costs nothing and takes a fifth off the file
        if (step === last && !wrapped) continue;
        d += d && !wrapped ? `L${step}` : `M${step}`;
        last = step;
      }
      if (d) commands.push(`${d}Z`);
    }
  }
}

const path = commands.join("");

const file = `// GENERATED by scripts/build-world-map.mjs — do not edit by hand.
//
// Country outlines from Natural Earth 110m (public domain), projected
// equirectangular into a ${360} x ${LAT_MAX - LAT_MIN} viewBox. Latitudes outside
// ${LAT_MIN}..${LAT_MAX} fall outside that box and are cropped by it.

export const WORLD_BOUNDS = { latMin: ${LAT_MIN}, latMax: ${LAT_MAX} };

/** Every country border as one path. */
export const WORLD_PATH = ${JSON.stringify(path)};

/** How many rings the path carries. */
export const WORLD_RINGS = ${commands.length};
`;

await writeFile(new URL("../src/data/worldMap.ts", import.meta.url), file);
console.log(
  `${commands.length} rings, ${(path.length / 1024).toFixed(0)}KB of path → src/data/worldMap.ts`,
);
